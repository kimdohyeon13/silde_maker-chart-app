/**
 * 정보 밀도에 따라 어노테이션 수를 조절하는 지침
 */
export function getDensityInstruction(
  density: "minimal" | "balanced" | "detailed"
): string {
  switch (density) {
    case "minimal":
      return `## 밀도: 미니멀 (유튜브 썸네일 / SNS용)
- 어노테이션: critical만 (최대 2개)
- 헤드라인과 핵심 수치 1개만 크게 표시
- 배경 깔끔, 격자선 없음
- 색상 2가지 이내`;

    case "balanced":
      return `## 밀도: 균형 (발표용 / 유튜브 영상 장표)
- 어노테이션: critical + high (총 5개 이내)
- 헤드라인 + 주요 수치 + 추세 화살표
- 보조선 최소화
- 호버 시 상세 정보`;

    case "detailed":
      return `## 밀도: 상세 (보고서 / 분석용)
- 어노테이션: 모든 중요도 포함
- 통계 요약 박스 표시
- 추세선 + 지지/저항선 포함
- 보조 격자선 표시
- 각주에 데이터 품질 정보 포함`;
  }
}

